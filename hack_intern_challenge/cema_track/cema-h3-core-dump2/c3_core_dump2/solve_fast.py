RCON = [0x00, 0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1b, 0x36]

def get_prev_round_key(rk, rcon_idx):
    w4, w5, w6, w7 = rk[0:4], rk[4:8], rk[8:12], rk[12:16]
    w3 = bytes([a^b for a,b in zip(w7, w6)])
    w2 = bytes([a^b for a,b in zip(w6, w5)])
    w1 = bytes([a^b for a,b in zip(w5, w4)])
    
    tmp = bytes([SBOX[w3[1]], SBOX[w3[2]], SBOX[w3[3]], SBOX[w3[0]]])
    rcon_word = bytes([RCON[rcon_idx], 0, 0, 0])
    w0 = bytes([a^b^c for a,b,c in zip(w4, tmp, rcon_word)])
    return w0 + w1 + w2 + w3

def derive_master_from_rk(rk, r):
    curr = rk
    for i in range(r, 0, -1):
        curr = get_prev_round_key(curr, i)
    return curr

def verify_key(key):
    cipher = Cipher(algorithms.AES(key), modes.CBC(iv), backend=default_backend())
    decryptor = cipher.decryptor()
    pt = decryptor.update(ciphertext) + decryptor.finalize()
    if b"Intern" in pt or b"Pro_Max" in pt or pt.isascii():
        print(f"Found valid key! {key.hex()}")
        print(pt)
        return True
    return False

print("Scanning for AES key schedule relation...")
for i in range(len(data) - 20):
    w0 = data[i:i+4]
    w3 = data[i+12:i+16]
    w4 = data[i+16:i+20]
    
    # Check if w4 == w0 ^ SubWord(RotWord(w3)) ^ RCON
    # which means w0 ^ w4 ^ SubWord(RotWord(w3)) == RCON
    v0 = w0[0] ^ w4[0] ^ SBOX[w3[1]]
    v1 = w0[1] ^ w4[1] ^ SBOX[w3[2]]
    v2 = w0[2] ^ w4[2] ^ SBOX[w3[3]]
    v3 = w0[3] ^ w4[3] ^ SBOX[w3[0]]
    
    if v1 == 0 and v2 == 0 and v3 == 0 and v0 in RCON and v0 != 0:
        r = RCON.index(v0)
        print(f"Found candidate at offset {hex(i)}, round {r}")
        # The 16 bytes starting at i+16 are round key r
        # wait! NO, the 16 bytes starting at i+16 are w4, w5, w6, w7.
        # But we don't know if w5, w6, w7 are intact.
        # However, w0, w1, w2, w3 starts at i. Let's assume the 16 bytes at `i` are round key r-1.
        # Or let's just grab the 16 bytes at i, derive backwards from r-1!
        rk_prev = data[i:i+16]
        try:
            mk = derive_master_from_rk(rk_prev, r - 1)
            print(f"Derived master key: {mk.hex()}")
            if verify_key(mk):
                sys.exit(0)
        except Exception as e:
            print(e)
            
        # What if w0, w1, w2, w3 are NOT intact, but w4, w5, w6, w7 are?
        # We can derive backwards from r using data[i+16:i+32].
        if i + 32 <= len(data):
            rk_curr = data[i+16:i+32]
            try:
                mk = derive_master_from_rk(rk_curr, r)
                print(f"Derived master key (from rk_curr): {mk.hex()}")
                if verify_key(mk):
                    sys.exit(0)
            except Exception as e:
                print(e)

print("Done scanning.")
