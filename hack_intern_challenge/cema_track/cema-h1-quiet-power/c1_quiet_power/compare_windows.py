HW = np.array([bin(x).count("1") for x in range(256)], dtype=np.uint8)

def run_cpa(traces, plaintexts, label=""):
    T = traces.astype(np.float32)
    tm = T.mean(axis=0)
    tc = T - tm
    tss = np.sum(tc**2, axis=0)
    
    recovered = []
    for b in range(16):
        scores = []
        for g in range(256):
            hyp = SBOX[plaintexts[:, b] ^ g]
            preds = HW[hyp].astype(np.float32)
            pc = preds - preds.mean()
            pss = float(np.sum(pc**2))
            if pss == 0: continue
            cov = np.dot(pc, tc)
            corr = cov / np.sqrt(pss * tss)
            peak = float(np.max(np.abs(corr)))
            scores.append((peak, g))
        scores.sort(reverse=True)
        recovered.append(scores[:5])
    return recovered

